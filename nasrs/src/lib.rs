//! nasrs：用户态软件镜像（RAID1）。
//!
//! 分层：
//!   mirror.rs  纯镜像规划（无 IO，可单测）—— 比对两个目录的清单，产出计划
//!   sync.rs    镜像的执行层：真的读目录、写文件的地方
//!   main.rs    参数解析 + 起进程（`nasrs mirror ...`）
//!
//! 原来的 RAID0 路线（raid.rs 的条带映射 + nbd.rs 的协议编解码）已整条删除。
//! 理由写在页面上：那条链缺导出通路，`serve` 算完布局就退出码 3，从未端到端
//! 跑通过。Qt 页里那一格改用第三方 mergerfs（FUSE 合并目录），不需要自研的
//! 块设备导出，也就不需要这两个模块。
//!
//! 本 crate 刻意**不**依赖任何内核模块、不要求 root：镜像是普通用户权限的文件
//! 拷贝，这是它能今天就跑通的原因，也是它与 mergerfs 的分工边界。

pub mod mirror;
pub mod sync;
